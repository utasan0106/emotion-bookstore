// Local static compiler. No adoption, publishing, network, tracking or storage.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {catalogue,bookProposals,HOST}=require('./work-catalogue');
const covers=require('./work-cover-source.json');
const uiReference=require('./editorial-proposals/ui-reference.json');
const root=path.resolve(__dirname,'..'), input=path.join(__dirname,'editorial-proposals');
const marker='<!-- Generated by tools/build-editorial-pages.js; approved inputs only. -->';
const escape=value=>String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const validIsbn=isbn=>/^\d{13}$/.test(isbn)&&[...isbn].reduce((n,c,i)=>n+Number(c)*(i%2?3:1),0)%10===0;
function validateBook(book) {
  const proof=require('./editorial-proposals/cover-provenance.json').assets.find(a=>a.isbn===book.isbn);
  for(const name of ['title','creator','author','publisher','editionLabel','isbn','bookPublishedOn','sourceUrl','sourceCheckedOn','fact','reason','basisNote']) if(!book[name]) throw Error('Missing book evidence: '+book.key+' '+name);
  if(book.author!==book.creator||!validIsbn(book.isbn)||!book.editionLabel.includes(book.isbn)) throw Error('Book author/edition mismatch: '+book.key);
  for(const value of [book.bookPublishedOn,book.sourceCheckedOn]) if(!/^\d{4}-\d{2}-\d{2}$/.test(value)||!Number.isFinite(Date.parse(value))||new Date(value).toISOString().slice(0,10)!==value) throw Error('Invalid source date: '+book.key);
  if(!proof||proof.title!==book.title||proof.author!==book.author||proof.sourcePage!==book.sourceUrl
      ||proof.file!==book.cover.file||proof.width!==book.cover.width||proof.height!==book.cover.height||proof.credit!==book.cover.credit) throw Error('Cover/edition evidence mismatch: '+book.key);
  if(book.cover.path!=='/assets/editorial-books/'+book.isbn+'.jpg'||book.cover.file!==book.isbn+'.jpg') throw Error('Unsafe cover path: '+book.key);
  const bytes=fs.readFileSync(path.join(input,'assets',book.cover.file));
  if(crypto.createHash('sha256').update(bytes).digest('hex')!==proof.sha256) throw Error('Reviewed cover bytes changed: '+book.key);
  if(!Array.isArray(book.sources)||!book.sources.length||book.sources.some(s=>!/^https:\/\//.test(s.url))) throw Error('Missing source links: '+book.key);
  return bytes;
}
function coverFor(work) {
  if(work.origin==='editorial') return {imageUrl:work.cover.path,width:work.cover.width,height:work.cover.height,credit:work.cover.credit,sourceUrl:work.sourceUrl};
  const cover=covers[work.key];
  return cover?.status==='usable'&&cover.imageUrl.startsWith('/')?cover:null;
}
function art(work) {
  const m=coverFor(work);
  if(!m) return `<div class="work-art"><div class="type-art" aria-hidden="true"><span>作品紹介</span><strong>${escape(work.kind==='book'?'本':work.kind==='film'?'映画':'作品')}</strong><span>文字で紹介</span></div></div>`;
  return `<div class="work-art"><a href="${escape(work.path)}"><img src="${escape(m.imageUrl)}" width="${m.width}" height="${m.height}" alt="${escape(work.creator)}『${escape(work.title)}』書影" loading="lazy"></a></div>`;
}
function credit(work) {
  const m=coverFor(work);
  const noMedia=uiReference.existingDisplay[work.key]?.noMediaNote;
  return m?`<p class="credit">${escape(m.credit)} <a href="${escape(m.sourceUrl)}">出典 ↗</a></p>`:noMedia?`<p class="credit">${escape(noMedia)} <a href="${escape(work.url)}">出典 ↗</a></p>`:'';
}
function edition(work) {
  if(work.origin==='editorial') return work.editionLabel;
  const detail=uiReference.existingDisplay[work.key];
  if(!detail||detail.title!==work.title) throw Error('Missing matched B display identity: '+work.key);
  const isbn=detail.edition.match(/ISBN (\d{13})/);
  if(isbn&&covers[work.key]?.isbn!==isbn[1]) throw Error('B display edition differs from existing ledger: '+work.key);
  return detail.edition;
}
function shelfEntry(cat) {
  return cat.shelves.length?{label:'棚をのぞく',path:'/works.html#editorial-shelves'}:{label:'作品を探す',path:'/works.html'};
}
